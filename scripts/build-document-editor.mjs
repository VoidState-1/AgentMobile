import fs from 'node:fs/promises';
import path from 'node:path';
import { Buffer } from 'node:buffer';
import { build } from 'esbuild';

const root = path.resolve('src/features/document/browser');
const result = await build({
  entryPoints: [path.join(root, 'editor.js')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: ['chrome100', 'safari16'],
  minify: true,
  legalComments: 'inline',
  metafile: true,
});
const packages = new Set();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = /node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input);
  if (match) packages.add(match[1]);
}
const licenses = [];
for (const name of [...packages].sort()) {
  const directory = path.resolve('node_modules', name);
  const info = JSON.parse(await fs.readFile(path.join(directory, 'package.json'), 'utf8'));
  const license = (await fs.readdir(directory)).find(file => /^licen[cs]e(?:[.-].+)?$/i.test(file));
  if (!license) throw new Error('Missing license: ' + name);
  licenses.push(
    `${name}@${info.version}\n${await fs.readFile(path.join(directory, license), 'utf8')}`,
  );
}
const notices = licenses.join('\n\n========================\n\n');
const layout = await fs.readFile(path.join(root, 'layout.html'), 'utf8');
const styles =
  (await fs.readFile(path.resolve(root, '../markdown.css'), 'utf8')) +
  '\n' +
  (await fs.readFile(path.join(root, 'editor.css'), 'utf8'));
const script = `/*\n${notices.replace(/\*\//g, '* /')}\n*/\n${result.outputFiles[0].text}`.replace(
  /<\/script/gi,
  '<\\/script',
);
const html = layout
  .replace('/* EDITOR_STYLES */', () => styles)
  .replace('/* EDITOR_SCRIPT */', () => script);
async function writeChanged(file, content) {
  if ((await fs.readFile(file, 'utf8').catch(() => undefined)) !== content)
    await fs.writeFile(file, content);
}
await writeChanged(
  path.resolve('src/features/document/generated.ts'),
  `// Generated by scripts/build-document-editor.mjs. Do not edit.\nexport const documentHtml = ${JSON.stringify(html)};\n`,
);
await fs.mkdir('licenses', { recursive: true });
await writeChanged('licenses/document-editor.txt', notices);
process.stdout.write(
  `Document editor built: ${Math.round(Buffer.byteLength(html) / 1024)} KiB, ${packages.size} licensed packages.\n`,
);
